from datetime import date

from fastapi import FastAPI
from fastapi.testclient import TestClient

from app.routers import recommendations
from app.routers.auth import get_current_admin
from app.schemas.recommendation import RecommendationHistoryItem


def test_public_today_recommendation_reads_existing_record_without_generation(monkeypatch) -> None:
    app = FastAPI()
    app.include_router(recommendations.router)

    async def override_database():
        yield object()

    async def read_existing(_db):
        return {
            "date": date.today(),
            "title": "Existing public recommendation",
            "type": "note",
            "reason": "Already persisted.",
            "target": None,
            "action_label": None,
            "source": None,
        }

    monkeypatch.setattr(recommendations, "read_today_recommendation", read_existing)
    app.dependency_overrides[recommendations.get_db] = override_database

    with TestClient(app) as client:
        response = client.get("/api/recommendations/today")

    assert response.status_code == 200
    assert response.json()["title"] == "Existing public recommendation"


