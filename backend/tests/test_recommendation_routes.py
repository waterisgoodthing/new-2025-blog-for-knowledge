def test_administrator_generates_today_recommendation_explicitly(monkeypatch) -> None:
    app = FastAPI()
    app.include_router(recommendations.router)

    async def override_database():
        yield object()

    async def override_admin():
        return object()

    async def generate(_db):
        return {
            "date": date.today(),
            "title": "Generated by an administrator request",
            "type": "note",
            "reason": "Explicit mutation.",
            "target": None,
            "action_label": None,
            "source": None,
        }

    monkeypatch.setattr(recommendations, "generate_daily_recommendation", generate)
    app.dependency_overrides[recommendations.get_db] = override_database
    app.dependency_overrides[get_current_admin] = override_admin

    with TestClient(app) as client:
        response = client.post("/api/recommendations/today/generate")

    assert response.status_code == 201
    assert response.json()["title"] == "Generated by an administrator request"


